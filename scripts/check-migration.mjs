import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {LsgStore} from '../src/core/db.mjs';
import {LsgService} from '../src/core/service.mjs';

const source=path.resolve(process.argv[2]||'data/lsg.sqlite');
if(!fs.existsSync(source))throw new Error('Provide an existing database path');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'lsg-migration-'));
const copy=path.join(dir,'migration.sqlite');
const original=new DatabaseSync(source,{readOnly:true});
original.exec(`VACUUM INTO '${copy.replaceAll("'","''")}'`);
original.close();
const backup=path.join(dir,'original.sqlite');fs.copyFileSync(copy,backup);
const before=new DatabaseSync(copy,{readOnly:true});
const snapshot=db=>db.prepare('SELECT id,version,metadata_json FROM nodes ORDER BY id').all();
const nodes=snapshot(before),schema=before.prepare("SELECT value FROM meta WHERE key='schema_version'").get().value;
before.close();
const store=new LsgStore(copy),service=new LsgService(store);
assert.deepEqual(snapshot(store.db),nodes);
assert.equal(store.db.prepare("SELECT value FROM meta WHERE key='schema_version'").get().value,'9');
assert.equal(store.db.prepare('PRAGMA integrity_check').get().integrity_check,'ok');
assert.equal(store.db.prepare('PRAGMA foreign_key_check').all().length,0);
const projects=store.listProjects().map(p=>({id:p.id,...service.workspace.progress({project_id:p.id}).counts}));
assert.equal(service.activity.sessions.size,0);
store.close();
console.log(JSON.stringify({ok:true,source_schema:schema,target_schema:9,preserved_nodes:nodes.length,projects,backup,migrated_copy:copy},null,2));
